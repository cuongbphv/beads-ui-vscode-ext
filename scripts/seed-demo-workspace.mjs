#!/usr/bin/env node
/**
 * Create the throwaway "Harbor" workspace the screenshots and the GIF are taken
 * against.
 *
 *   node scripts/seed-demo-workspace.mjs            # into the OS temp dir
 *   node scripts/seed-demo-workspace.mjs --out D:\demo\harbor
 *   node scripts/seed-demo-workspace.mjs --force    # replace an existing one
 *
 * Why a separate workspace at all: every screenshot used to be taken against
 * this repo's own tracker, which is 98% closed, so all three tabs skewed Done
 * and the product looked finished rather than alive. The alternative — editing
 * the project's real beads until they photograph well — is not an alternative.
 *
 * Two hard rules, both enforced below rather than trusted:
 *   1. the demo workspace is created *outside* this repository, and
 *   2. every `bd` call is pinned to it with `-C`, after asserting that the
 *      directory has its own `.beads` and an empty database.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildDemoJsonl, demoSummary, DEMO_ACTOR, DEMO_PREFIX } from './lib/demo-project.mjs';
import { defaultDemoDir } from './lib/demo-workspace.mjs';
import { seedFleetDemo } from './lib/fleet-demo-seed.mjs';

const repoRoot = resolve(join(dirname(fileURLToPath(import.meta.url)), '..'));

const argv = process.argv.slice(2);
const force = argv.includes('--force');
const outArg = (() => {
  const index = argv.indexOf('--out');
  return index >= 0 ? argv[index + 1] : undefined;
})();

/** Default: the OS temp dir. The folder name is what the editor title bar shows. */
const outDir = resolve(outArg ?? defaultDemoDir());

/** Never let a demo seed touch the extension's own tracker. */
function assertOutsideRepo(dir) {
  const rel = relative(repoRoot, dir);
  const inside = rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
  if (inside) {
    throw new Error(
      `refusing to seed inside the repository (${dir}).\n` +
        `The demo workspace must be its own folder so bd cannot reach ${join(repoRoot, '.beads')}.`,
    );
  }
}

function run(command, args, options = {}) {
  return execFileSync(command, args, {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, BD_JSON_ENVELOPE: '0', BD_NON_INTERACTIVE: '1' },
    ...options,
  });
}

/**
 * `bd`, always pinned to the demo directory.
 *
 * `-C` is the strong form — bd refuses it outright unless that directory really
 * is a beads project, which is exactly the guard we want on every call that
 * touches data. `bd init` is the one command that cannot use it (there is no
 * project yet), so it runs with `cwd` instead, in a directory we have just
 * created and `git init`-ed so bd cannot walk up into anything of ours.
 */
function bd(args) {
  return run('bd', ['-C', outDir, ...args]);
}

assertOutsideRepo(outDir);

if (existsSync(join(outDir, '.beads'))) {
  if (!force) {
    console.error(
      `${outDir} is already a beads workspace.\n` +
        `Re-run with --force to delete and re-seed it, or pass --out <dir>.`,
    );
    process.exit(1);
  }
  console.log(`› removing the previous demo workspace`);
  rmSync(outDir, { recursive: true, force: true });
}

mkdirSync(outDir, { recursive: true });

// A bare folder makes for a bleak Explorer pane behind the dashboard, and bd
// prefers a repository root it can anchor to.
writeFileSync(
  join(outDir, 'README.md'),
  [
    '# Harbor',
    '',
    'Deploy dashboard for small teams. Demo workspace for the Beads Dashboard',
    'extension — the issues here are fixtures, generated by',
    '`scripts/seed-demo-workspace.mjs`.',
    '',
  ].join('\n'),
);
writeFileSync(
  join(outDir, '.gitignore'),
  ['node_modules/', 'dist/', ''].join('\n'),
);

// Who "you" are in this project. Without it the sidebar's Needs You section
// resolves the identity bd would use — the git user of whoever is running the
// capture — and the demo's most important section photographs empty.
mkdirSync(join(outDir, '.vscode'), { recursive: true });
writeFileSync(
  join(outDir, '.vscode', 'settings.json'),
  `${JSON.stringify({ 'beadsDashboard.assignee': DEMO_ACTOR }, null, 2)}\n`,
);

try {
  run('git', ['init', '-q'], { cwd: outDir });
} catch {
  // git is optional here; bd works without it, the workspace is throwaway.
}

console.log(`› bd init in ${outDir}`);
run(
  'bd',
  [
    'init',
    '--prefix',
    DEMO_PREFIX,
    '--non-interactive',
    '--role',
    'maintainer',
    '--skip-agents',
    '--skip-hooks',
    '--quiet',
  ],
  { cwd: outDir },
);

if (!existsSync(join(outDir, '.beads'))) {
  throw new Error(`bd init did not create ${join(outDir, '.beads')}`);
}

const existing = Number(JSON.parse(bd(['count', '--json'])).count ?? 0);
if (existing !== 0) {
  throw new Error(`expected a fresh database, found ${existing} issues in ${outDir}`);
}

const jsonlPath = join(outDir, '.beads', 'demo-seed.jsonl');
writeFileSync(jsonlPath, buildDemoJsonl());
console.log(`› importing ${jsonlPath}`);
bd(['import', jsonlPath]);

const summary = demoSummary();
const imported = Number(JSON.parse(bd(['count', '--json'])).count ?? 0);
if (imported !== summary.total) {
  throw new Error(`imported ${imported} issues, expected ${summary.total}`);
}

// One ad-hoc human gate, so the sidebar's "Needs You" section — the whole
// point of that view — has something to show besides the issue queue. This
// runs after the count check above: `bd gate create` files its own gate
// issue, which would otherwise throw off the imported-vs-expected count.
console.log(`› creating a sample human gate`);
bd([
  'gate',
  'create',
  '--blocks',
  'harbor-306',
  '--reason',
  'Confirm final tax-inclusive pricing copy with legal before this ships.',
]);

// A Fleet scenario: a worker actively "on" harbor-201 in a real wt-* git
// worktree, with a transcript rich enough to show off the markdown renderer.
console.log(`› seeding a Fleet worker + worktree`);
const fleetWorktreePath = seedFleetDemo(outDir);
console.log(`  worktree   ${fleetWorktreePath}`);

const stats = JSON.parse(bd(['stats', '--json']));
console.log('\n✔ demo workspace ready');
console.log(`  path       ${outDir}`);
console.log(`  issues     ${imported}`);
console.log(`  status     ${JSON.stringify(summary.byStatus)}`);
console.log(`  types      ${JSON.stringify(summary.byType)}`);
console.log(`  assignees  ${JSON.stringify(summary.byAssignee)}`);
console.log(`  burn-up    ${summary.closedSpanDays} days of close history`);
console.log(`  bd stats   ${JSON.stringify(stats.summary ?? stats)}`);
console.log(`\nNext:  npm run capture -- --workspace "${outDir}"`);
